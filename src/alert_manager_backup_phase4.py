def extract_spatial_risk_info(density_map: Any) -> Dict[str, Any]:
    """
    Analyzes a 4x4 density grid matrix to identify the primary risk zone (cell with max density),
    its density value, human-readable description, and any tied secondary zones.
    
    Grid layout (4x4):
        Rows:    A (top), B (upper-middle), C (lower-middle), D (bottom)
        Columns: 1 (left), 2 (left-center), 3 (right-center), 4 (right)
    """
    ROW_LETTERS = ['A', 'B', 'C', 'D']
    ROW_LABELS = {'A': 'Top', 'B': 'Upper', 'C': 'Lower', 'D': 'Bottom'}
    COL_LABELS = {'1': 'Left', '2': 'Left-Center', '3': 'Right-Center', '4': 'Right'}

    def format_description(cell_id: str) -> str:
        row_char = cell_id[0]
        col_char = cell_id[1]
        r_desc = ROW_LABELS.get(row_char, "Unknown")
        c_desc = COL_LABELS.get(col_char, "Unknown")
        if "-" in c_desc:
            return f"{r_desc}/{c_desc}"
        return f"{r_desc}-{c_desc}"

    if density_map is None:
        return {
            "primary_risk_zone": "A1",
            "primary_zone_density": 0,
            "zone_description": "Top-Left",
            "secondary_zones": []
        }

    try:
        grid = np.array(density_map)
        if grid.shape != (4, 4):
            return {
                "primary_risk_zone": "A1",
                "primary_zone_density": 0,
                "zone_description": "Top-Left",
                "secondary_zones": []
            }
    except Exception:
        return {
            "primary_risk_zone": "A1",
            "primary_zone_density": 0,
            "zone_description": "Top-Left",
            "secondary_zones": []
        }

    max_val = -1
    best_cell = "A1"
    tied_cells = []

    for r in range(4):
        for c in range(4):
            val = int(grid[r, c])
            cell_id = f"{ROW_LETTERS[r]}{c + 1}"
            if val > max_val:
                max_val = val
                best_cell = cell_id
                tied_cells = [cell_id]
            elif val == max_val and max_val > 0:
                tied_cells.append(cell_id)

    secondary = [cell for cell in tied_cells if cell != best_cell]

    return {
        "primary_risk_zone": best_cell,
        "primary_zone_density": max(0, max_val),
        "zone_description": format_description(best_cell),
        "secondary_zones": secondary
    }


@dataclass
class AlertEvent:
    """Represents a discrete alert event generated by a camera risk transition."""
    alert_id: str
    camera_id: str
    camera_name: str
    timestamp: str
    risk_level: str          # "MEDIUM", "HIGH", "CRITICAL"
    risk_score: float        # 0.0 to 100.0
    reason: str              # Derived human-readable reason
    status: str              # "ACTIVE", "ESCALATED", "RESOLVED", "ACKNOWLEDGED"
    details: Dict[str, Any] = field(default_factory=dict)
    acknowledged: bool = False
    acknowledged_at: Optional[str] = None
    acknowledged_by: Optional[str] = None
    resolved_at: Optional[str] = None
    resolved_by: Optional[str] = None
    alarm_played: bool = False
    primary_risk_zone: str = "A1"
    primary_zone_density: int = 0
    zone_description: str = "Top-Left"
    severity: str = "LOW"    # "LOW", "MEDIUM", "HIGH", "CRITICAL"
    category: str = "CROWD_RISK"  # "CRITICAL_DENSITY", "HIGH_RISK", "MEDIUM_RISK", "RAPID_INFLUX", "ABNORMAL_MOTION"
    crowd_density: int = 0
    person_count: int = 0
    timestamp_unix: int = 0

    def __post_init__(self):
        if self.severity == "LOW" and self.risk_level:
            self.severity = self.risk_level
        if not self.risk_level and self.severity:
            self.risk_level = self.severity
        if self.timestamp_unix == 0:
            try:
                dt = datetime.fromisoformat(self.timestamp)
                self.timestamp_unix = int(dt.timestamp())
            except Exception:
                self.timestamp_unix = int(time.time())
        if self.crowd_density == 0:
            self.crowd_density = self.primary_zone_density or int(self.details.get("max_density", self.details.get("density", 0)))
        if self.person_count == 0:
            self.person_count = int(self.details.get("person_count", self.details.get("visible_heads", self.details.get("head_count", 0))))

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        # Convenience aliases for callers
        d["density"] = self.crowd_density
        d["alert_category"] = self.category
        d["trigger_reason"] = self.reason
        return d


def derive_alert_category(telemetry: Dict[str, Any], severity: str) -> str:
    """Categorizes the primary trigger condition into an alert category."""
    max_density = telemetry.get("max_density", telemetry.get("density", 0))
    growth_rate = telemetry.get("growth_rate", 0.0)
    avg_speed = telemetry.get("avg_speed", 0.0)
    anomaly_score = telemetry.get("anomaly_score", telemetry.get("anomaly", 0.0))
    
    if severity == "CRITICAL" or max_density >= 30:
        return "CRITICAL_DENSITY"
    elif growth_rate >= 3.0:
        return "RAPID_INFLUX"
    elif avg_speed >= 2.5 or anomaly_score >= 0.5:
        return "ABNORMAL_MOTION"
    elif severity == "HIGH":
        return "HIGH_RISK"
    elif severity == "MEDIUM":
        return "MEDIUM_RISK"
    return "CROWD_RISK"


def derive_alert_reason(telemetry: Dict[str, Any]) -> str:
    """
    Extracts a human-readable reason string from existing telemetry sub-scores/factors
    without altering or creating new AI risk formulas.
    """
    reasons = []
    
    max_density = telemetry.get("max_density", telemetry.get("density", 0))
    growth_rate = telemetry.get("growth_rate", 0.0)
    avg_speed = telemetry.get("avg_speed", 0.0)
    anomaly_score = telemetry.get("anomaly_score", telemetry.get("anomaly", 0.0))
    risk_score = telemetry.get("risk_score", telemetry.get("combined_score", 0.0))
    
    if max_density >= 30:
        reasons.append(f"Critical Crowd Density ({int(max_density)} persons/cell)")
    elif max_density >= 15:
        reasons.append(f"High Crowd Density ({int(max_density)} persons/cell)")
    elif max_density >= 5:
        reasons.append(f"Elevated Density ({int(max_density)} persons/cell)")
        
    if growth_rate >= 3.0:
        reasons.append(f"Sudden Crowd Surge (+{growth_rate:.1f} p/s)")
    elif growth_rate >= 2.0:
        reasons.append(f"Rapid Crowd Influx (+{growth_rate:.1f} p/s)")
        
    if avg_speed >= 2.5:
        reasons.append(f"Abnormal Motion Speed ({avg_speed:.1f} px/f)")
        
    if anomaly_score >= 0.5:
        reasons.append(f"High Local Motion Anomaly ({anomaly_score:.2f})")

    if not reasons:
        reasons.append(f"Combined Crowd Risk (Score: {risk_score:.1f}/100)")

    return " | ".join(reasons)


class CameraAlertTracker:
    """
    State machine managing independent alert transitions for a single camera stream.
    
    Transition rules:
    - LOW -> MEDIUM/HIGH/CRITICAL: Generates a new ACTIVE alert.
    - Escalation (lower -> higher level): Generates an ESCALATED alert.
    - Sustained (same level): Suppresses duplicate alert events within cooldown window;
      updates active alert metrics in-place.
    - De-escalation (higher -> lower non-LOW): Updates active alert level and metrics in-place.
    - Return to LOW: Resolves active alert (status = RESOLVED).
    """
    LEVEL_RANKS = {"LOW": 0, "MEDIUM": 1, "HIGH": 2, "CRITICAL": 3}

    def __init__(
        self,
        camera_id: str,
        camera_name: str,
        cooldown_seconds: float = 30.0,
        config: Optional[Dict[str, Any]] = None
    ):
        self.camera_id = camera_id
        self.camera_name = camera_name
        self.cooldown_seconds = cooldown_seconds
        self.config = {**DEFAULT_ALERT_CONFIG, **(config or {})}
        self.critical_density_threshold = self.config.get("critical_density_threshold", 50)
        
        self.current_risk_level: str = "LOW"
        self.active_alert: Optional[AlertEvent] = None
        self.last_alert_time: Optional[float] = None
        self.alert_counter: int = 0

    def acknowledge_alert(self, operator_id: str = "Operator") -> bool:
        """Marks the active alert as acknowledged without resolving underlying camera risk."""
        if self.active_alert is not None and not self.active_alert.acknowledged:
            self.active_alert.acknowledged = True
            self.active_alert.status = "ACKNOWLEDGED"
            self.active_alert.acknowledged_at = datetime.now().isoformat()
            self.active_alert.acknowledged_by = operator_id
            return True
        return False

    def resolve_alert(self, operator_id: str = "Operator", note: Optional[str] = None) -> Optional[AlertEvent]:
        """Manually resolves active alert for this camera tracker."""
        if self.active_alert is not None:
            self.active_alert.status = "RESOLVED"
            self.active_alert.resolved_at = datetime.now().isoformat()
            self.active_alert.resolved_by = operator_id
            if note:
                self.active_alert.details["resolution_note"] = note
            resolved = self.active_alert
            self.active_alert = None
            self.current_risk_level = "LOW"
            return resolved
        return None

    def process_telemetry(self, telemetry: Dict[str, Any]) -> Tuple[Optional[AlertEvent], Optional[AlertEvent]]:
        """
        Evaluates frame telemetry snapshot and updates alert state.
        
        Returns:
            Tuple of (new_or_escalated_alert_event, resolved_alert_event)
        """
        raw_level = str(telemetry.get("severity", telemetry.get("risk_level", telemetry.get("risk", "LOW")))).upper()
        if raw_level not in self.LEVEL_RANKS:
            raw_level = "LOW"
            
        risk_score = float(telemetry.get("risk_score", telemetry.get("combined_score", 0.0)))
        curr_time = time.time()
        timestamp_str = telemetry.get("last_frame_time") or datetime.now().isoformat()
        
        spatial_info = extract_spatial_risk_info(telemetry.get("density_map"))
        pz = str(telemetry.get("primary_risk_zone", spatial_info["primary_risk_zone"]))
        pzd = int(telemetry.get("primary_zone_density", spatial_info["primary_zone_density"]))
        zd = str(telemetry.get("zone_description", spatial_info["zone_description"]))
        
        telemetry["primary_risk_zone"] = pz
        telemetry["primary_zone_density"] = pzd
        telemetry["zone_description"] = zd
        
        max_density = int(telemetry.get("max_density", telemetry.get("density", pzd)))
        person_count = int(telemetry.get("person_count", telemetry.get("visible_heads", telemetry.get("head_count", 0))))

        # Critical density check: if density satisfies critical threshold and not explicitly LOW
        new_level = raw_level
        if max_density >= self.critical_density_threshold and raw_level != "LOW":
            new_level = "CRITICAL"

        category = str(telemetry.get("category", telemetry.get("alert_category", "")))
        if not category:
            category = derive_alert_category(telemetry, new_level)
            
        reason = str(telemetry.get("trigger_reason", telemetry.get("reason", "")))
        if not reason:
            reason = derive_alert_reason(telemetry)

        current_rank = self.LEVEL_RANKS.get(self.current_risk_level, 0)
        new_rank = self.LEVEL_RANKS.get(new_level, 0)

        # Rule 1: Transition to LOW -> Resolve any active alert
        if new_level == "LOW":
            resolved_alert = None
            if self.active_alert is not None:
                self.active_alert.status = "RESOLVED"
                self.active_alert.resolved_at = timestamp_str
                resolved_alert = self.active_alert
                self.active_alert = None
            self.current_risk_level = "LOW"
            return None, resolved_alert

        def _create_event(status_label: str) -> AlertEvent:
            self.alert_counter += 1
            alert_id = f"ALT_{self.camera_id}_{int(curr_time)}_{self.alert_counter:03d}"
            return AlertEvent(
                alert_id=alert_id,
                camera_id=self.camera_id,
                camera_name=self.camera_name,
                timestamp=timestamp_str,
                risk_level=new_level,
                risk_score=risk_score,
                reason=reason,
                status=status_label,
                severity=new_level,
                category=category,
                crowd_density=max_density,
                person_count=person_count,
                details=dict(telemetry),
                acknowledged=False,
                alarm_played=False,
                primary_risk_zone=pz,
                primary_zone_density=pzd,
                zone_description=zd,
                timestamp_unix=int(curr_time)
            )

        # Rule 2: Escalation to genuinely higher level (e.g. MEDIUM -> HIGH, HIGH -> CRITICAL)
        if new_rank > current_rank and current_rank > 0:
            triggered = _create_event("ESCALATED")
            self.active_alert = triggered
            self.last_alert_time = curr_time
            self.current_risk_level = new_level
            return triggered, None

        # Rule 3: Initial Transition from LOW (e.g. LOW -> MEDIUM, LOW -> HIGH, LOW -> CRITICAL)
        if current_rank == 0 and new_rank > 0:
            triggered = _create_event("ACTIVE")
            self.active_alert = triggered
            self.last_alert_time = curr_time
            self.current_risk_level = new_level
            return triggered, None

        # Rule 4: Sustained Risk (new_rank == current_rank)
        if new_rank == current_rank and new_rank > 0:
            if self.last_alert_time is None or (curr_time - self.last_alert_time) >= self.cooldown_seconds:
                # Re-trigger alert after cooldown if risk remains active
                triggered = _create_event("ACTIVE")
                self.active_alert = triggered
                self.last_alert_time = curr_time
                return triggered, None
            else:
                # Within cooldown: update active alert metrics in-place without creating a duplicate event
                if self.active_alert is not None:
                    self.active_alert.risk_score = risk_score
                    self.active_alert.crowd_density = max_density
                    self.active_alert.person_count = person_count
                    self.active_alert.primary_risk_zone = pz
                    self.active_alert.primary_zone_density = pzd
                    self.active_alert.zone_description = zd
                    self.active_alert.details = dict(telemetry)
                return None, None

        # Rule 5: De-escalation (e.g. CRITICAL -> HIGH, HIGH -> MEDIUM)
        if new_rank < current_rank and new_rank > 0:
            self.current_risk_level = new_level
            if self.active_alert is not None:
                self.active_alert.risk_level = new_level
                self.active_alert.severity = new_level
                self.active_alert.risk_score = risk_score
                self.active_alert.crowd_density = max_density
                self.active_alert.person_count = person_count
                self.active_alert.primary_risk_zone = pz
                self.active_alert.primary_zone_density = pzd
                self.active_alert.zone_description = zd
                self.active_alert.details = dict(telemetry)
            return None, None

        self.current_risk_level = new_level
        return None, None


class AlertManager:
    """
    Central Alert Management service for CrowdPatrol multi-camera monitoring.
    Features:
    - Automated Alert Generation from telemetry snapshots
    - Complete Lifecycle operations: generate, active, history, acknowledge, resolve, get_by_id
    - Per-camera isolated state tracking (CAM-01, CAM-02, DIRECT-01, etc.)
    - Cooldown debounce and duplicate suppression
    - Emergency alarm sound triggers
    - Local fallback persistence (CSV logging under logs/alerts.csv)
    - Firebase Realtime Database persistence & synchronization
    - Event listener dispatch system
    """
    def __init__(
        self,
        cooldown_seconds: float = 30.0,
        enable_local_logging: bool = True,
        csv_path: Optional[Path] = None,
        firebase_alert_manager: Optional[Any] = None,
        config: Optional[Dict[str, Any]] = None,
        notification_dispatcher: Optional[Any] = None
    ):
        self.cooldown_seconds = cooldown_seconds
        self.enable_local_logging = enable_local_logging
        self.csv_path = Path(csv_path) if csv_path else LOGS_DIR / "alerts.csv"
        self.fb_manager = firebase_alert_manager
        self.notification_dispatcher = notification_dispatcher
        self.config = {**DEFAULT_ALERT_CONFIG, **(config or {})}
        self.config["cooldown_seconds"] = cooldown_seconds
        
        self.camera_trackers: Dict[str, CameraAlertTracker] = {}
        self.active_alerts: Dict[str, AlertEvent] = {}  # key: camera_id -> active AlertEvent
        self.alert_history: List[AlertEvent] = []
        self.event_listeners: List[Callable[[AlertEvent], None]] = []

        if self.notification_dispatcher and hasattr(self.notification_dispatcher, "as_alert_listener"):
            self.register_listener(self.notification_dispatcher.as_alert_listener())

        if self.enable_local_logging:
            self._init_csv_log()

    def attach_notification_dispatcher(self, dispatcher: Any):
        """Attaches a NotificationDispatcher and registers its event listener."""
        self.notification_dispatcher = dispatcher
        if hasattr(dispatcher, "as_alert_listener"):
            self.register_listener(dispatcher.as_alert_listener())

    def _init_csv_log(self):
        """Ensure local CSV log file exists with complete schema headers."""
        try:
            self.csv_path.parent.mkdir(parents=True, exist_ok=True)
            if not self.csv_path.exists():
                with open(self.csv_path, "w", newline="", encoding="utf-8") as f:
                    writer = csv.writer(f)
                    writer.writerow([
                        "alert_id", "camera_id", "camera_name", "timestamp",
                        "risk_level", "risk_score", "reason", "status",
                        "primary_risk_zone", "primary_zone_density",
                        "acknowledged", "acknowledged_by",
                        "severity", "category", "crowd_density", "person_count",
                        "resolved_at", "resolved_by"
                    ])
        except Exception as e:
            print(f"[!] AlertManager CSV init warning: {e}")

    def register_listener(self, listener: Callable[[AlertEvent], None]):
        """Register callback listener invoked whenever an alert is created/updated."""
        if listener not in self.event_listeners:
            self.event_listeners.append(listener)

    def generate_alert(
        self,
        camera_id: str,
        camera_name: str,
        severity: str,
        category: str,
        risk_score: float,
        crowd_density: int,
        person_count: int,
        reason: str,
        details: Optional[Dict[str, Any]] = None
    ) -> Optional[AlertEvent]:
        """
        Explicit programmatic alert generation hook.
        Evaluates alert state and creates an AlertEvent if conditions permit.
        """
        telemetry = {
            "severity": severity,
            "risk_level": severity,
            "category": category,
            "risk_score": risk_score,
            "combined_score": risk_score,
            "max_density": crowd_density,
            "density": crowd_density,
            "person_count": person_count,
            "reason": reason,
            **(details or {})
        }
        return self.process_camera_telemetry(camera_id, camera_name, telemetry)

    def acknowledge_alert(self, identifier: str, operator_id: str = "Operator") -> bool:
        """
        Acknowledges active alert by camera_id (e.g. 'CAM-01') OR alert_id (e.g. 'ALT_...').
        Updates state in local tracker, active list, and Firebase.
        """
        target_alert = None
        # Check if identifier matches a camera_id
        if identifier in self.camera_trackers:
            tracker = self.camera_trackers[identifier]
            ok = tracker.acknowledge_alert(operator_id=operator_id)
            if ok and tracker.active_alert:
                target_alert = tracker.active_alert
        else:
            # Check if identifier matches an alert_id
            for tracker in self.camera_trackers.values():
                if tracker.active_alert and tracker.active_alert.alert_id == identifier:
                    ok = tracker.acknowledge_alert(operator_id=operator_id)
                    if ok:
                        target_alert = tracker.active_alert
                    break
            if not target_alert:
                for alt in self.alert_history:
                    if alt.alert_id == identifier:
                        alt.acknowledged = True
                        alt.status = "ACKNOWLEDGED"
                        alt.acknowledged_at = datetime.now().isoformat()
                        alt.acknowledged_by = operator_id
                        target_alert = alt
                        break

        if target_alert:
            if self.fb_manager and hasattr(self.fb_manager, "update_alert_status"):
                try:
                    self.fb_manager.update_alert_status(
                        target_alert.alert_id,
                        camera_id=target_alert.camera_id,
                        status="ACKNOWLEDGED",
                        acknowledged_by=operator_id
                    )
                except Exception as e:
                    print(f"[!] Firebase alert ack sync warning: {e}. Local state preserved.")
            elif self.fb_manager and hasattr(self.fb_manager, "mark_alert_acknowledged"):
                try:
                    self.fb_manager.mark_alert_acknowledged(target_alert.alert_id, acknowledged_by=operator_id)
                except Exception as e:
                    print(f"[!] Firebase alert ack sync warning: {e}. Local state preserved.")
            self._notify_listeners(target_alert)
            return True
        return False

    def resolve_alert(self, identifier: str, operator_id: str = "Operator", note: Optional[str] = None) -> bool:
        """
        Manually resolves an alert by camera_id or alert_id.
        Removes alert from active status but preserves historical record in alert_history.
        """
        resolved_alert = None
        cam_id = None
        if identifier in self.camera_trackers:
            cam_id = identifier
            tracker = self.camera_trackers[identifier]
            resolved_alert = tracker.resolve_alert(operator_id=operator_id, note=note)
        else:
            # Search by alert_id in trackers
            for tracker in self.camera_trackers.values():
                if tracker.active_alert and tracker.active_alert.alert_id == identifier:
                    cam_id = tracker.camera_id
                    resolved_alert = tracker.resolve_alert(operator_id=operator_id, note=note)
                    break
            if not resolved_alert:
                # Search by alert_id in history
                for alt in self.alert_history:
                    if alt.alert_id == identifier:
                        alt.status = "RESOLVED"
                        alt.resolved_at = datetime.now().isoformat()
                        alt.resolved_by = operator_id
                        if note:
                            alt.details["resolution_note"] = note
                        resolved_alert = alt
                        break

        if resolved_alert:
            if cam_id and cam_id in self.active_alerts:
                del self.active_alerts[cam_id]
            # Ensure resolved record is in history
            if resolved_alert not in self.alert_history:
                self.alert_history.append(resolved_alert)
            if self.fb_manager and hasattr(self.fb_manager, "update_alert_status"):
                try:
                    self.fb_manager.update_alert_status(
                        resolved_alert.alert_id,
                        camera_id=resolved_alert.camera_id,
                        status="RESOLVED",
                        resolved_by=operator_id
                    )
                except Exception as e:
                    print(f"[!] Firebase alert resolution sync warning: {e}. Local state preserved.")
            self._log_alert_locally(resolved_alert)
            self._notify_listeners(resolved_alert)
            return True
        return False

    def get_alert_by_id(self, alert_id: str) -> Optional[AlertEvent]:
        """Retrieves an alert event by its unique alert_id from active alerts or history."""
        for alt in self.active_alerts.values():
            if alt.alert_id == alert_id:
                return alt
        for alt in reversed(self.alert_history):
            if alt.alert_id == alert_id:
                return alt
        return None

    def process_camera_telemetry(self, camera_id: str, camera_name: str, telemetry: Dict[str, Any]) -> Optional[AlertEvent]:
        """
        Main entry point: processes telemetry snapshot for a specific camera stream.
        """
        if camera_id not in self.camera_trackers:
            self.camera_trackers[camera_id] = CameraAlertTracker(
                camera_id=camera_id,
                camera_name=camera_name,
                cooldown_seconds=self.cooldown_seconds,
                config=self.config
            )
            
        tracker = self.camera_trackers[camera_id]
        tracker.camera_name = camera_name  # Ensure name is updated if changed
        
        new_alert, resolved_alert = tracker.process_telemetry(telemetry)
        
        # Handle resolution
        if resolved_alert is not None:
            if camera_id in self.active_alerts:
                del self.active_alerts[camera_id]
            self.alert_history.append(resolved_alert)
            self._log_alert_locally(resolved_alert)
            self._sync_to_firebase(resolved_alert)
            self._notify_listeners(resolved_alert)
            
        # Handle new/escalated alert
        if new_alert is not None:
            self.active_alerts[camera_id] = new_alert
            self.alert_history.append(new_alert)
            self._log_alert_locally(new_alert)
            self._sync_to_firebase(new_alert)
            self._notify_listeners(new_alert)
            return new_alert

        return None

    def _log_alert_locally(self, alert: AlertEvent):
        """Append alert event to local CSV log file."""
        if not self.enable_local_logging:
            return
        try:
            with open(self.csv_path, "a", newline="", encoding="utf-8") as f:
                writer = csv.writer(f)
                writer.writerow([
                    alert.alert_id,
                    alert.camera_id,
                    alert.camera_name,
                    alert.timestamp,
                    alert.risk_level,
                    f"{alert.risk_score:.2f}",
                    alert.reason,
                    alert.status,
                    alert.primary_risk_zone,
                    alert.primary_zone_density,
                    alert.acknowledged,
                    alert.acknowledged_by or "",
                    alert.severity,
                    alert.category,
                    alert.crowd_density,
                    alert.person_count,
                    alert.resolved_at or "",
                    alert.resolved_by or ""
                ])
        except Exception as e:
            print(f"[!] Local alert CSV write failure: {e}")

    def _sync_to_firebase(self, alert: AlertEvent):
        """Syncs alert event to Firebase if FirebaseAlertManager is connected."""
        if self.fb_manager is None:
            return
        try:
            if hasattr(self.fb_manager, "store_camera_alert"):
                self.fb_manager.store_camera_alert(alert.to_dict())
            elif hasattr(self.fb_manager, "store_alert"):
                self.fb_manager.store_alert(
                    risk_level=alert.risk_level,
                    density=alert.crowd_density,
                    anomaly_score=alert.details.get("anomaly_score", 0.0),
                    person_count=alert.person_count,
                    combined_score=alert.risk_score,
                    primary_risk_zone=alert.primary_risk_zone,
                    primary_zone_density=alert.primary_zone_density
                )
        except Exception as e:
            if not getattr(self, "_firebase_sync_warned", False):
                print(f"[!] Firebase alert sync warning: {e}. Local alert operation continues.")
                self._firebase_sync_warned = True

    def _notify_listeners(self, alert: AlertEvent):
        """Invoke registered callback functions for alert event."""
        for listener in self.event_listeners:
            try:
                listener(alert)
            except Exception as e:
                print(f"[!] Alert listener error: {e}")

    def get_active_alerts(self) -> List[AlertEvent]:
        """Returns list of currently active or escalated alerts across all cameras."""
        return list(self.active_alerts.values())

    def get_unacknowledged_high_alerts(self) -> List[AlertEvent]:
        """Returns list of active HIGH / CRITICAL / ESCALATED risk alerts that have NOT been acknowledged."""
        return [
            alt for alt in self.active_alerts.values()
            if (alt.risk_level in ["HIGH", "CRITICAL"] or alt.severity in ["HIGH", "CRITICAL"]) and not alt.acknowledged
        ]

    def get_pending_alarm_alerts(self) -> List[AlertEvent]:
        """
        Returns list of active HIGH / CRITICAL / ESCALATED risk alerts needing sound alarm trigger.
        Marks returned alerts with alarm_played = True so sound plays only once per HIGH/CRITICAL event.
        """
        pending = []
        for alt in self.active_alerts.values():
            if (alt.risk_level in ["HIGH", "CRITICAL"] or alt.severity in ["HIGH", "CRITICAL"]) and not alt.acknowledged and not alt.alarm_played:
                alt.alarm_played = True
                pending.append(alt)
        return pending

    def get_alert_history(
        self,
        limit: int = 50,
        status: Optional[str] = None,
        camera_id: Optional[str] = None
    ) -> List[AlertEvent]:
        """Returns recent alert history across all cameras with optional status and camera_id filtering."""
        filtered = self.alert_history
        if camera_id:
            filtered = [a for a in filtered if a.camera_id == camera_id]
        if status:
            filtered = [a for a in filtered if a.status == status]
        return filtered[-limit:]

    def get_alert_summary(self) -> Dict[str, int]:
        """
        Returns high-level count summary of alerts across the system:
        - active: total active alerts
        - critical: alerts with CRITICAL severity
        - high: alerts with HIGH severity
        - medium: alerts with MEDIUM severity
        - resolved: total resolved alerts in history
        - total_history: total alerts in historical ledger
        """
        active = list(self.active_alerts.values())
        resolved_count = sum(1 for a in self.alert_history if a.status == "RESOLVED")
        return {
            "active": len(active),
            "critical": sum(1 for a in active if a.severity == "CRITICAL" or a.risk_level == "CRITICAL"),
            "high": sum(1 for a in active if a.severity == "HIGH" or a.risk_level == "HIGH"),
            "medium": sum(1 for a in active if a.severity == "MEDIUM" or a.risk_level == "MEDIUM"),
            "resolved": resolved_count,
            "total_history": len(self.alert_history)
        }

    def get_camera_alert_status(self, camera_id: str) -> Optional[AlertEvent]:
        """Returns active alert event for a specific camera, or None if normal/low."""
        return self.active_alerts.get(camera_id)

    def clear_all(self):
        """Reset internal alert manager state."""
        self.active_alerts.clear()
        self.alert_history.clear()
        self.camera_trackers.clear()
